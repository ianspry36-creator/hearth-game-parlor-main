export type Country = {
  /**
   * ISO 3166-1 alpha-2 code (mapped to a regional-indicator flag glyph), or an
   * ISO 3166-2 subdivision code such as `GB-ENG` for the UK home nations.
   */
  code: string;
  name: string;
};

/** The UK home nations have no ISO alpha-2 code, so they render from flagcdn. */
const SUBDIVISION_FLAG_URLS: Record<string, string> = {
  "GB-ENG": "https://flagcdn.com/gb-eng.svg",
  "GB-SCT": "https://flagcdn.com/gb-sct.svg",
  "GB-WLS": "https://flagcdn.com/gb-wls.svg",
  "GB-NIR": "https://flagcdn.com/gb-nir.svg",
};

/**
 * Build a Twemoji flag SVG URL from an ISO 3166-1 alpha-2 country code, mirroring
 * the Twemoji approach used for animal/object avatars so flags render the same on
 * every platform (Windows does not render flag emoji natively). Subdivision codes
 * are redirected to their flagcdn SVG instead.
 */
export function flagUrl(code: string): string {
  const subdivision = SUBDIVISION_FLAG_URLS[code];
  if (subdivision) return subdivision;
  const codepoints = [...code.toLowerCase()].map((char) =>
    (0x1f1e6 + char.charCodeAt(0) - 97).toString(16),
  );
  return `https://cdn.jsdelivr.net/gh/twitter/twemoji@14.0.2/assets/svg/${codepoints.join("-")}.svg`;
}

